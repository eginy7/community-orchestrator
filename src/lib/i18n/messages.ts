export const MESSAGES: Record<Locale, Messages> = { he, en };

type Leaves<T> = { [A in keyof T & string]: { [K in keyof T[A] & string]: `${A}.${K}` }[keyof T[A] & string] }[keyof T & string];
/** Dotted "area.key" path into the dictionary. */
export type MessageKey = Leaves<Messages>;

export type Vars = Record<string, string | number>;
export type TFunction = (key: MessageKey, vars?: Vars) => string;

/** Build a `t(key, vars?)` for one locale. `{name}` placeholders are replaced from `vars`. */
export function createT(locale: Locale): TFunction {
  const dict = MESSAGES[locale] ?? MESSAGES[DEFAULT_LOCALE];
  return (key, vars) => {
    const dot = key.indexOf(".");
    const area = key.slice(0, dot) as keyof Messages;
    const leaf = key.slice(dot + 1);
    const raw = (dict[area] as Record<string, string> | undefined)?.[leaf] ?? (MESSAGES.he[area] as Record<string, string> | undefined)?.[leaf] ?? key;
    return vars ? interpolate(raw, vars) : raw;
  };
}

export function interpolate(template: string, vars: Vars): string {
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
